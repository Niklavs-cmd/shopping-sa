"""Regenerate the committed synthetic, fixed-price problem instances.

Run from any directory: python scripts/generate_instances.py
Only Python's standard library is required. No store or price data is scraped.
All monetary values are integer euro cents; a price is for one unit.
"""

from __future__ import annotations

import json
import random
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
INSTANCE_DIR = ROOT / "instances"

PRODUCTS = (
    "Kafija 500 g", "Tēja 40 maisiņi", "Rīsi 1 kg", "Makaroni 500 g",
    "Auzu pārslas 1 kg", "Olīveļļa 500 ml", "Konservēti tomāti 400 g",
    "Pupiņas 400 g", "Milti 1 kg", "Cukurs 1 kg", "Šokolāde 100 g",
    "Rieksti 200 g", "Sula 1 l", "Cepumi 250 g", "Medus 500 g",
    "Zobu pasta 75 ml", "Ziepes 100 g", "Šampūns 250 ml",
    "Trauku mazgāšanas līdzeklis 500 ml", "Papīra dvieļi 2 ruļļi",
)

# (name, number of products, number of shops, seed, missing probability, mode)
SCENARIOS = (
    ("small_06x03", 6, 3, 6103, 0.10, "mixed"),
    ("small_08x04", 8, 4, 8104, 0.22, "no_free"),
    ("small_10x04", 10, 4, 10104, 0.25, "thresholds"),
    ("small_12x03", 12, 3, 12103, 0.18, "high_thresholds"),
    ("medium_20x05", 20, 5, 20105, 0.25, "mixed"),
    ("medium_40x06", 40, 6, 40106, 0.32, "thresholds"),
    ("large_80x08", 80, 8, 80108, 0.40, "high_thresholds"),
    ("large_120x10", 120, 10, 120110, 0.45, "mixed"),
)


def make_instance(name: str, n: int, m: int, seed: int,
                  missing_probability: float, mode: str) -> dict:
    """Prices, quantities and availability are determined solely by the seed."""
    rng = random.Random(seed)
    stores = []
    # The average per-shop subtotal rises with instance size. Thresholds are
    # scaled accordingly, so delivery remains relevant for larger instances.
    scale = max(3500, round(n * 700 / m / 100) * 100)
    for j in range(m):
        if mode == "no_free" or (mode == "mixed" and j % 3 == 0):
            threshold = None
        elif mode == "high_thresholds":
            threshold = scale * (3 + j % 2)
        else:
            threshold = round(scale * (0.8 + 0.2 * (j % 4)) / 100) * 100
        stores.append({
            "name": f"Veikals {chr(65 + j)}",
            "delivery_cents": rng.choice((299, 399, 499, 599, 749, 899, 1199)),
            "free_delivery_threshold_cents": threshold,
        })
    items = []
    for i in range(n):
        base = rng.randint(120, 1190)
        quantity = rng.choices((1, 2, 3), weights=(7, 2, 1))[0]
        prices = []
        for j in range(m):
            if rng.random() < missing_probability:
                prices.append(None)
            else:
                # Rotating discounts create competing cheapest shops.
                percent = rng.randint(87, 120) - (15 if j == i % m else 0)
                prices.append(max(1, (base * percent + 50) // 100))
        if all(price is None for price in prices):
            prices[rng.randrange(m)] = base
        items.append({
            "name": f"P{i + 1:03d}: {PRODUCTS[i % len(PRODUCTS)]}",
            "quantity": quantity,
            "prices_cents": prices,
        })
    count = 1
    for item in items:
        count *= sum(price is not None for price in item["prices_cents"])
    return {
        "name": name,
        "metadata": {
            "source": "Synthetic teaching data; no real store prices or scraping.",
            "currency": "EUR",
            "price_unit": "integer cents per unit",
            "seed": seed,
            "scenario": mode,
            "availability_probability": 1 - missing_probability,
            "feasible_assignments": count,
            "identity_rule": "Each P-code is one identical product across all stores.",
            "quantity_rule": "All units of an item are assigned to the same store.",
        },
        "stores": stores,
        "items": items,
    }


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Explicit UTF-8 and LF keep generated bytes stable across platforms.
    path.write_bytes((json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))


def main() -> None:
    for spec in SCENARIOS:
        instance = make_instance(*spec)
        write_json(INSTANCE_DIR / f"{spec[0]}.json", instance)
        print(f"{spec[0]}: {instance['metadata']['feasible_assignments']} feasible assignments")
    write_json(INSTANCE_DIR / "edge_cases" / "shipping_barrier.json", {
        "name": "shipping_barrier",
        "metadata": {
            "source": "Synthetic exact counterexample.",
            "known_optimum_cents": 2200,
            "known_optimal_assignments": [[0, 0], [1, 1]],
            "cheapest_items_assignment": [0, 1],
            "cheapest_items_total_cents": 3200,
            "explanation": "Each cheapest item costs 1000; consolidation meets the 2200 free-delivery threshold.",
        },
        "stores": [
            {"name": "Veikals A", "delivery_cents": 600, "free_delivery_threshold_cents": 2200},
            {"name": "Veikals B", "delivery_cents": 600, "free_delivery_threshold_cents": 2200},
        ],
        "items": [
            {"name": "P001", "quantity": 1, "prices_cents": [1000, 1200]},
            {"name": "P002", "quantity": 1, "prices_cents": [1200, 1000]},
        ],
    })
    write_json(INSTANCE_DIR / "edge_cases" / "forced_and_zero.json", {
        "name": "forced_and_zero",
        "metadata": {"source": "Synthetic edge case.", "known_optimum_cents": 1500},
        "stores": [
            {"name": "Veikals A", "delivery_cents": 500, "free_delivery_threshold_cents": None},
            {"name": "Veikals B", "delivery_cents": 400, "free_delivery_threshold_cents": 1000},
            {"name": "Unused", "delivery_cents": 999, "free_delivery_threshold_cents": None},
        ],
        "items": [
            {"name": "Free item", "quantity": 2, "prices_cents": [0, None, None]},
            {"name": "Threshold item", "quantity": 2, "prices_cents": [None, 500, None]},
        ],
    })


if __name__ == "__main__":
    main()
